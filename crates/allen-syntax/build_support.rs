pub struct Inputs<'a> {
    pub grammar: &'a str,
    pub production_map: &'a str,
    pub kind_ids: &'a str,
    pub lexical_kinds: &'a str,
    pub language_spec: &'a str,
}

#[derive(Debug)]
pub struct Generated {
    pub kinds: String,
    pub ast: String,
    pub inventory: String,
}

impl Generated {
    pub fn files(&self) -> [(&str, &[u8]); 3] {
        [
            ("kinds.rs", self.kinds.as_bytes()),
            ("ast.rs", self.ast.as_bytes()),
            ("inventory.rs", self.inventory.as_bytes()),
        ]
    }
}

pub fn render(inputs: &Inputs<'_>) -> Result<Generated, String> {
    let grammar = inputs
        .grammar
        .parse::<Grammar>()
        .map_err(|error| format!("invalid ungrammar: {error}"))?;
    let documented = documented_productions(inputs.language_spec)?;
    let mapping = parse_mapping(inputs.production_map)?;
    validate_mapping(&grammar, &documented, &mapping)?;
    let ids = parse_kind_ids(inputs.kind_ids)?;
    let lexical = parse_lexical_kinds(inputs.lexical_kinds)?;
    validate_kind_ids(&grammar, &lexical, &ids)?;
    let typed_ast = typed_ast_model(&grammar)?;

    Ok(Generated {
        kinds: render_kinds(&grammar, &lexical, &ids),
        ast: render_ast(&grammar, &typed_ast),
        inventory: render_inventory(&grammar, &mapping, &lexical, &typed_ast),
    })
}

fn parse_lexical_kinds(text: &str) -> Result<BTreeSet<String>, String> {
    let kinds = text
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(ToOwned::to_owned)
        .collect::<BTreeSet<_>>();
    let expected = REQUIRED_LEXICAL_KINDS.map(ToOwned::to_owned).into();
    if kinds != expected {
        return Err(
            "lexical kind inventory must contain every required trivia and tombstone kind".into(),
        );
    }
    Ok(kinds)
}

fn documented_productions(specification: &str) -> Result<BTreeSet<String>, String> {
    let start = specification
        .find(GRAMMAR_FENCE_HEADER)
        .ok_or("language specification has no section 3.4 grammar fence")?;
    let grammar = &specification[start + GRAMMAR_FENCE_HEADER.len()..];
    let grammar = grammar
        .split_once("\n```")
        .ok_or("language specification grammar fence is not closed")?
        .0;
    let names = grammar
        .lines()
        .filter_map(|line| line.split_once('=').map(|(left, _)| left.trim()))
        .filter(|name| {
            !name.is_empty()
                && name
                    .bytes()
                    .all(|byte| byte.is_ascii_lowercase() || byte == b'-')
        })
        .map(ToOwned::to_owned)
        .collect::<BTreeSet<_>>();
    if names.is_empty() {
        return Err("language specification grammar fence has no productions".into());
    }
    Ok(names)
}

fn parse_mapping(text: &str) -> Result<BTreeMap<String, String>, String> {
    let mut result = BTreeMap::new();
    for (line_number, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (production, node) = split_tsv(line)
            .ok_or_else(|| format!("production map line {} must contain a tab", line_number + 1))?;
        if production.is_empty()
            || node.is_empty()
            || result.insert(production.into(), node.into()).is_some()
        {
            return Err(format!(
                "invalid or duplicate production map line {}",
                line_number + 1
            ));
        }
    }
    Ok(result)
}

fn validate_mapping(
    grammar: &Grammar,
    documented: &BTreeSet<String>,
    mapping: &BTreeMap<String, String>,
) -> Result<(), String> {
    let mapped = mapping.keys().cloned().collect::<BTreeSet<_>>();
    if &mapped != documented {
        let missing = documented.difference(&mapped).cloned().collect::<Vec<_>>();
        let orphan = mapped.difference(documented).cloned().collect::<Vec<_>>();
        return Err(format!(
            "production map mismatch; missing={missing:?}, orphan={orphan:?}"
        ));
    }
    let nodes = grammar
        .iter()
        .map(|node| grammar[node].name.clone())
        .collect::<BTreeSet<_>>();
    let mapped_nodes = mapping.values().cloned().collect::<BTreeSet<_>>();
    if nodes != mapped_nodes {
        let missing = nodes.difference(&mapped_nodes).cloned().collect::<Vec<_>>();
        let orphan = mapped_nodes.difference(&nodes).cloned().collect::<Vec<_>>();
        return Err(format!(
            "grammar node mapping mismatch; missing={missing:?}, orphan={orphan:?}"
        ));
    }
    Ok(())
}

fn parse_kind_ids(text: &str) -> Result<BTreeMap<String, u16>, String> {
    let mut result = BTreeMap::new();
    let mut used = BTreeSet::new();
    for (line_number, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (name, raw_id) = split_tsv(line)
            .ok_or_else(|| format!("kind ID line {} must contain a tab", line_number + 1))?;
        let id = raw_id
            .parse::<u16>()
            .map_err(|_| format!("kind ID line {} has an invalid ID", line_number + 1))?;
        if name.is_empty() || result.insert(name.into(), id).is_some() || !used.insert(id) {
            return Err(format!(
                "duplicate kind name or ID on line {}",
                line_number + 1
            ));
        }
    }
    Ok(result)
}

fn split_tsv(line: &str) -> Option<(&str, &str)> {
    line.split_once('\t')
}

fn validate_kind_ids(
    grammar: &Grammar,
    lexical: &BTreeSet<String>,
    ids: &BTreeMap<String, u16>,
) -> Result<(), String> {
    let mut expected = BTreeSet::from(["special:ERROR".to_owned()]);
    expected.extend(
        grammar
            .tokens()
            .map(|token| format!("token:{}", grammar[token].name)),
    );
    expected.extend(
        grammar
            .iter()
            .map(|node| format!("node:{}", grammar[node].name)),
    );
    expected.extend(lexical.iter().cloned());
    let actual = ids.keys().cloned().collect::<BTreeSet<_>>();
    if expected != actual {
        let missing = expected.difference(&actual).cloned().collect::<Vec<_>>();
        let orphan = actual.difference(&expected).cloned().collect::<Vec<_>>();
        return Err(format!(
            "stable kind ID mismatch; missing={missing:?}, orphan={orphan:?}"
        ));
    }
    if ids.get("special:ERROR") != Some(&0) {
        return Err("special:ERROR must retain stable ID 0".into());
    }
    let mut variants = BTreeSet::new();
    for key in ids {
        if !variants.insert(kind_variant(key.0)) {
            return Err(format!(
                "kind names produce a duplicate Rust variant: {}",
                key.0
            ));
        }
    }
    Ok(())
}

fn render_kinds(
    grammar: &Grammar,
    lexical: &BTreeSet<String>,
    ids: &BTreeMap<String, u16>,
) -> String {
    let mut entries = ids
        .iter()
        .map(|(name, id)| (*id, name.as_str()))
        .collect::<Vec<_>>();
    entries.sort_unstable();
    let mut output = String::from(MARKER);
    output.push_str("#[repr(u16)]\n#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]\npub enum SyntaxKind {\n");
    for (id, name) in &entries {
        output.push_str(&format!("    {} = {id},\n", kind_variant(name)));
    }
    output.push_str("}\n\nimpl SyntaxKind {\n    #[must_use]\n    pub const fn from_raw(raw: u16) -> Option<Self> {\n        match raw {\n");
    for (id, name) in &entries {
        output.push_str(&format!(
            "            {id} => Some(Self::{}),\n",
            kind_variant(name)
        ));
    }
    output.push_str("            _ => None,\n        }\n    }\n\n    #[must_use]\n    pub const fn is_token(self) -> bool {\n        matches!(self,\n");
    let token_variants = grammar
        .tokens()
        .map(|token| kind_variant(&format!("token:{}", grammar[token].name)))
        .chain(
            lexical
                .iter()
                .filter(|kind| {
                    kind.starts_with("trivia:")
                        || *kind == "token:@"
                        || *kind == "special:ERROR_TOKEN"
                })
                .map(|kind| kind_variant(kind)),
        )
        .collect::<Vec<_>>();
    output.push_str(&format!(
        "            {}\n",
        token_variants
            .iter()
            .map(|variant| format!("Self::{variant}"))
            .collect::<Vec<_>>()
            .join(" | ")
    ));
    output.push_str("        )\n    }\n}\n");
    output
}

fn render_ast(grammar: &Grammar, typed_ast: &[TypedNode]) -> String {
    let mut output = String::from(MARKER);
    output.push_str(AST_PRELUDE);
    for typed_node in typed_ast.iter().filter(|node| !node.labels.is_empty()) {
        output.push_str(&format!(
            "const AST_PATTERN_{}: AstPattern = {};\n\n",
            snake(&grammar[typed_node.node].name).to_ascii_uppercase(),
            render_pattern(
                &grammar[typed_node.node].rule,
                grammar,
                &typed_node.labels,
                None
            ),
        ));
    }
    for typed_node in typed_ast {
        let name = &grammar[typed_node.node].name;
        output.push_str(&format!("#[derive(Clone, Debug, Eq, Hash, PartialEq)]\npub struct {name} {{ syntax: SyntaxNode }}\n\n"));
        output.push_str(&format!("impl AstNode for {name} {{\n    type Language = AllenLanguage;\n\n    fn can_cast(kind: SyntaxKind) -> bool {{ kind == SyntaxKind::{} }}\n\n    fn cast(syntax: SyntaxNode) -> Option<Self> {{ Self::can_cast(syntax.kind()).then_some(Self {{ syntax }}) }}\n\n    fn syntax(&self) -> &SyntaxNode {{ &self.syntax }}\n}}\n\n", kind_variant(&format!("node:{name}"))));
        output.push_str(&format!("impl {name} {{\n    #[must_use]\n    pub fn children(&self) -> impl Iterator<Item = SyntaxNode> + '_ {{ self.syntax.children() }}\n\n    /// Returns recovery nodes and tokens owned directly by this grammar node.\n    #[must_use]\n    pub fn errors(&self) -> impl Iterator<Item = AstError> + '_ {{\n        self.syntax.children_with_tokens().filter_map(AstError::cast)\n    }}\n"));
        for accessor in &typed_node.accessors {
            render_accessor(&mut output, grammar, typed_node, accessor);
        }
        output.push_str("}\n\n");
    }
    if output.ends_with("\n\n") {
        output.pop();
    }
    output
}

fn render_inventory(
    grammar: &Grammar,
    mapping: &BTreeMap<String, String>,
    lexical: &BTreeSet<String>,
    typed_ast: &[TypedNode],
) -> String {
    let mut output = String::from(MARKER);
    output.push_str("/// Normative section 3.4 production to concrete-node mapping.\npub const PRODUCTION_INVENTORY: &[(&str, &str)] = &[\n");
    for (production, node) in mapping {
        output.push_str(&format!("    ({production:?}, {node:?}),\n"));
    }
    output.push_str("];\n\n/// Lexical terminals, represented as tokens rather than AST nodes.\npub const TOKEN_INVENTORY: &[&str] = &[\n");
    for token in grammar.tokens() {
        output.push_str(&format!("    {:?},\n", grammar[token].name));
    }
    output.push_str(
        "];\n\n/// Non-grammar lexical and recovery kinds.\npub const LEXICAL_KIND_INVENTORY: &[&str] = &[\n",
    );
    for kind in lexical {
        output.push_str(&format!("    {kind:?},\n"));
    }
    output.push_str(
        "];\n\n/// Concrete grammar node names.\npub const NODE_INVENTORY: &[&str] = &[\n",
    );
    for node in grammar.iter() {
        output.push_str(&format!("    {:?},\n", grammar[node].name));
    }
    output.push_str("];\n\n/// Grammar nodes with one generated public typed wrapper each.\npub const TYPED_AST_WRAPPER_INVENTORY: &[&str] = &[\n");
    for typed_node in typed_ast {
        output.push_str(&format!("    {:?},\n", grammar[typed_node.node].name));
    }
    output.push_str("];\n\n/// Exact direct-child/token accessor coverage: wrapper, method, target, cardinality, label.\n///\n/// Required and optional singular relationships both return `Option`; `many`\n/// relationships return typed iterators. An empty label denotes a homogeneous\n/// target-derived accessor. Every wrapper also exposes `errors`.\npub const TYPED_AST_ACCESSOR_INVENTORY: &[(&str, &str, &str, &str, &str)] = &[\n");
    for typed_node in typed_ast {
        let wrapper = &grammar[typed_node.node].name;
        for accessor in &typed_node.accessors {
            output.push_str(&format!(
                "    ({wrapper:?}, {:?}, {:?}, {:?}, {:?}),\n",
                accessor.method,
                accessor.target.inventory_name(grammar),
                accessor.cardinality.inventory_name(),
                accessor.label.as_deref().unwrap_or(""),
            ));
        }
    }
    output.push_str("];\n");
    output
}

