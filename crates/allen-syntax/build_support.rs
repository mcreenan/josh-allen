    fn formal_rule(document: &str, name: &str) -> String {
        let mut lines = document.lines().skip_while(|line| !line.starts_with(name));
        let first = lines
            .next()
            .unwrap_or_else(|| panic!("missing formal rule `{name}`"));
        std::iter::once(first)
            .chain(lines.take_while(|line| line.starts_with(' ')))
            .flat_map(str::split_whitespace)
            .collect::<Vec<_>>()
            .join(" ")
    }

    #[test]
    fn formal_grammar_copies_and_mechanical_rules_stay_in_sync() {
        let specification = include_str!("../../docs/language-spec.md");
        let agent_reference = include_str!("../../docs/agents/reference/allen-language.md");
        for rule in [
            "generic-parameters",
            "tuple-type",
            "function-type",
            "primary",
        ] {
            assert_eq!(
                formal_rule(agent_reference, rule),
                formal_rule(specification, rule),
                "formal grammar drift for {rule}"
            );
        }

        let grammar = include_str!("grammar/allen-0.1.ungram");
        for production in [
            "GenericParameters = '<' GenericParameter (',' GenericParameter)* ','? '>'",
            "TupleType = '(' (Type ',' (Type (',' Type)* ','?)?)? ')'",
            "FunctionType = 'fn' '(' (parameter_types:Type (',' parameter_types:Type)* ','?)? ')' 'returns' return_type:Type EffectClause?",
            "Primary = Literal | TemplateLiteral | 'identifier' | 'map' | 'Some' | 'Ok' | 'Err'",
        ] {
            assert!(
                grammar.contains(production),
                "mechanical grammar drift for `{production}`"
            );
        }
    }

