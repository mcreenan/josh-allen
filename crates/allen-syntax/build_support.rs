#[derive(Clone, Debug)]
enum PatternEdge {
    Epsilon(usize),
    Symbol(String, usize),
}

#[derive(Debug)]
struct PatternNfa {
    edges: Vec<Vec<PatternEdge>>,
    start: usize,
    accept: usize,
}

impl PatternNfa {
    fn from_rule(rule: &Rule, grammar: &Grammar) -> Self {
        let mut nfa = Self {
            edges: Vec::new(),
            start: 0,
            accept: 0,
        };
        let (start, accept) = nfa.fragment(rule, grammar);
        nfa.start = start;
        nfa.accept = accept;
        nfa
    }

    fn state(&mut self) -> usize {
        let state = self.edges.len();
        self.edges.push(Vec::new());
        state
    }

    fn epsilon(&mut self, from: usize, to: usize) {
        self.edges[from].push(PatternEdge::Epsilon(to));
    }

    fn fragment(&mut self, rule: &Rule, grammar: &Grammar) -> (usize, usize) {
        match rule {
            Rule::Node(node) => self.symbol(format!("node:{}", grammar[*node].name)),
            Rule::Token(token) => self.symbol(format!("token:{}", grammar[*token].name)),
            Rule::Labeled { rule, .. } => self.fragment(rule, grammar),
            Rule::Opt(rule) => {
                let start = self.state();
                let accept = self.state();
                let (inner_start, inner_accept) = self.fragment(rule, grammar);
                self.epsilon(start, accept);
                self.epsilon(start, inner_start);
                self.epsilon(inner_accept, accept);
                (start, accept)
            }
            Rule::Rep(rule) => {
                let start = self.state();
                let accept = self.state();
                let (inner_start, inner_accept) = self.fragment(rule, grammar);
                self.epsilon(start, accept);
                self.epsilon(start, inner_start);
                self.epsilon(inner_accept, inner_start);
                self.epsilon(inner_accept, accept);
                (start, accept)
            }
            Rule::Seq(rules) => {
                let start = self.state();
                let mut tail = start;
                for rule in rules {
                    let (next_start, next_accept) = self.fragment(rule, grammar);
                    self.epsilon(tail, next_start);
                    tail = next_accept;
                }
                (start, tail)
            }
            Rule::Alt(rules) => {
                let start = self.state();
                let accept = self.state();
                for rule in rules {
                    let (branch_start, branch_accept) = self.fragment(rule, grammar);
                    self.epsilon(start, branch_start);
                    self.epsilon(branch_accept, accept);
                }
                (start, accept)
            }
        }
    }

    fn symbol(&mut self, symbol: String) -> (usize, usize) {
        let start = self.state();
        let accept = self.state();
        self.edges[start].push(PatternEdge::Symbol(symbol, accept));
        (start, accept)
    }

    fn start_closure(&self) -> Vec<usize> {
        self.epsilon_closure([self.start])
    }

    fn epsilon_closure(&self, seeds: impl IntoIterator<Item = usize>) -> Vec<usize> {
        let mut closure = seeds.into_iter().collect::<BTreeSet<_>>();
        let mut pending = closure.iter().copied().collect::<Vec<_>>();
        while let Some(state) = pending.pop() {
            for edge in &self.edges[state] {
                if let PatternEdge::Epsilon(next) = edge {
                    if closure.insert(*next) {
                        pending.push(*next);
                    }
                }
            }
        }
        closure.into_iter().collect()
    }

    fn symbols(&self, states: &[usize]) -> BTreeSet<&str> {
        states
            .iter()
            .flat_map(|state| &self.edges[*state])
            .filter_map(|edge| match edge {
                PatternEdge::Symbol(symbol, _) => Some(symbol.as_str()),
                PatternEdge::Epsilon(_) => None,
            })
            .collect()
    }

    fn advance(&self, states: &[usize], symbol: &str) -> Vec<usize> {
        self.epsilon_closure(states.iter().flat_map(|state| {
            self.edges[*state].iter().filter_map(|edge| match edge {
                PatternEdge::Symbol(candidate, next) if candidate == symbol => Some(*next),
                PatternEdge::Epsilon(_) | PatternEdge::Symbol(_, _) => None,
            })
        }))
    }

    fn accepts(&self, states: &[usize]) -> bool {
        states.binary_search(&self.accept).is_ok()
    }
}

#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
struct DecoderPair {
    left: Vec<usize>,
    right: Vec<usize>,
    boundaries_differ: bool,
}

fn validate_observable_repetitions(
    rule: &Rule,
    grammar: &Grammar,
    owner: &str,
) -> Result<(), String> {
    match rule {
        Rule::Rep(repeated) => {
            if repetition_boundaries_are_ambiguous(repeated, grammar) {
                return Err(format!(
                    "typed AST repetition ambiguity on {owner}: repeated child/token pattern permits different iteration boundaries"
                ));
            }
            validate_observable_repetitions(repeated, grammar, owner)
        }
        Rule::Labeled { rule, .. } | Rule::Opt(rule) => {
            validate_observable_repetitions(rule, grammar, owner)
        }
        Rule::Seq(rules) | Rule::Alt(rules) => {
            for rule in rules {
                validate_observable_repetitions(rule, grammar, owner)?;
            }
            Ok(())
        }
        Rule::Node(_) | Rule::Token(_) => Ok(()),
    }
}

/// Returns true when the repeated body's direct-kind language has two distinct
/// iteration-boundary factorizations. The finite decoder-product search handles
/// alternatives, optionals, and nested repetitions without enumerating strings.
fn repetition_boundaries_are_ambiguous(rule: &Rule, grammar: &Grammar) -> bool {
    let nfa = PatternNfa::from_rule(rule, grammar);
    let start = nfa.start_closure();
    if nfa.accepts(&start) {
        return true;
    }

    let initial = DecoderPair {
        left: start.clone(),
        right: start.clone(),
        boundaries_differ: false,
    };
    let mut seen = BTreeSet::from([initial.clone()]);
    let mut pending = VecDeque::from([initial]);
    while let Some(pair) = pending.pop_front() {
        let left_symbols = nfa.symbols(&pair.left);
        let right_symbols = nfa.symbols(&pair.right);
        for symbol in left_symbols.intersection(&right_symbols) {
            let left = nfa.advance(&pair.left, symbol);
            let right = nfa.advance(&pair.right, symbol);
            let left_accepts = nfa.accepts(&left);
            let right_accepts = nfa.accepts(&right);
            // Both decoders have consumed the same direct-kind sequence. If
            // their earlier cuts differ and both can end here, the sequence has
            // two repetition factorizations and a seen endpoint would need
            // re-expansion to preserve every possible capture.
            if pair.boundaries_differ && left_accepts && right_accepts {
                return true;
            }

            let left_cuts = [false, true].into_iter().filter(|cut| !cut || left_accepts);
            let right_cuts = [false, true]
                .into_iter()
                .filter(|cut| !cut || right_accepts)
                .collect::<Vec<_>>();
            for left_cut in left_cuts {
                for &right_cut in &right_cuts {
                    let next = DecoderPair {
                        left: if left_cut {
                            start.clone()
                        } else {
                            left.clone()
                        },
                        right: if right_cut {
                            start.clone()
                        } else {
                            right.clone()
                        },
                        boundaries_differ: pair.boundaries_differ || left_cut != right_cut,
                    };
                    if seen.insert(next.clone()) {
                        pending.push_back(next);
                    }
                }
            }
        }
    }
    false
}

fn typed_ast_model(grammar: &Grammar) -> Result<Vec<TypedNode>, String> {
    grammar
        .iter()
        .map(|node| {
            let mut fields = Vec::new();
            collect_fields(&grammar[node].rule, None, &mut fields)?;
            let labels = fields
                .iter()
                .filter_map(|field| field.label.clone())
                .collect::<Vec<_>>();
            if !labels.is_empty() {
                validate_observable_repetitions(&grammar[node].rule, grammar, &grammar[node].name)?;
            }
            let mut used_methods = BTreeSet::from([
                "children".to_owned(),
                "errors".to_owned(),
                "syntax".to_owned(),
            ]);
            let accessors = fields
                .into_iter()
                .map(|field| {
                    let count = field_count(
                        &grammar[node].rule,
                        field.target,
                        field.label.as_deref(),
                        None,
                    );
                    let cardinality = count.cardinality();
                    let method =
                        accessor_method(grammar, field.target, cardinality, field.label.as_deref());
                    if !used_methods.insert(method.clone()) {
                        return Err(format!(
                            "typed AST accessor collision on {}.{method} for {}",
                            grammar[node].name,
                            field.target.inventory_name(grammar),
                        ));
                    }
                    let selector = field
                        .label
                        .as_ref()
                        .map(|label| {
                            labels
                                .iter()
                                .position(|candidate| candidate == label)
                                .and_then(|index| u16::try_from(index).ok())
                                .map(AccessorSelector::Label)
                                .ok_or_else(|| {
                                    format!("too many typed AST labels on {}", grammar[node].name)
                                })
                        })
                        .transpose()?
                        .unwrap_or(AccessorSelector::Aggregate);
                    Ok(Accessor {
                        target: field.target,
                        cardinality,
                        method,
                        label: field.label,
                        selector,
                    })
                })
                .collect::<Result<Vec<_>, String>>()?;
            Ok(TypedNode {
                node,
                accessors,
                labels,
            })
        })
        .collect()
}

fn collect_fields(
    rule: &Rule,
    active_label: Option<&str>,
    fields: &mut Vec<FieldKey>,
) -> Result<(), String> {
    match rule {
        Rule::Node(node) => push_unique_field(
            fields,
            FieldKey {
                target: AccessorTarget::Node(*node),
                label: active_label.map(ToOwned::to_owned),
            },
        )?,
        Rule::Token(token) => push_unique_field(
            fields,
            FieldKey {
                target: AccessorTarget::Token(*token),
                label: active_label.map(ToOwned::to_owned),
            },
        )?,
        Rule::Labeled { label, rule } => {
            if active_label.is_some() {
                return Err(format!("nested typed AST label `{label}` is unsupported"));
            }
            collect_fields(rule, Some(label), fields)?;
        }
        Rule::Opt(rule) | Rule::Rep(rule) => {
            collect_fields(rule, active_label, fields)?;
        }
        Rule::Seq(rules) | Rule::Alt(rules) => {
            for rule in rules {
                collect_fields(rule, active_label, fields)?;
            }
        }
    }
    Ok(())
}

fn push_unique_field(fields: &mut Vec<FieldKey>, field: FieldKey) -> Result<(), String> {
    if let Some(label) = &field.label {
        if let Some(previous) = fields
            .iter()
            .find(|candidate| candidate.label.as_ref() == Some(label))
        {
            if previous.target != field.target {
                return Err(format!(
                    "typed AST label `{label}` refers to more than one target"
                ));
            }
            return Ok(());
        }
    }
    if !fields.contains(&field) {
        fields.push(field);
    }
    Ok(())
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct Count {
    min: u8,
    max: u8,
}

impl Count {
    const ZERO: Self = Self { min: 0, max: 0 };
    const ONE: Self = Self { min: 1, max: 1 };

    fn cardinality(self) -> Cardinality {
        match (self.min, self.max) {
            (1, 1) => Cardinality::Required,
            (0, 1) => Cardinality::Optional,
            _ => Cardinality::Many,
        }
    }

    fn sequence(self, other: Self) -> Self {
        Self {
            min: self.min.saturating_add(other.min).min(2),
            max: self.max.saturating_add(other.max).min(2),
        }
    }

    fn alternative(self, other: Self) -> Self {
        Self {
            min: self.min.min(other.min),
            max: self.max.max(other.max),
        }
    }
}

fn field_count(
    rule: &Rule,
    target: AccessorTarget,
    label: Option<&str>,
    active_label: Option<&str>,
) -> Count {
    match rule {
        Rule::Node(node) => {
            Count::from(AccessorTarget::Node(*node) == target && active_label == label)
        }
        Rule::Token(token) => {
            Count::from(AccessorTarget::Token(*token) == target && active_label == label)
        }
        Rule::Labeled {
            label: rule_label,
            rule,
        } => field_count(rule, target, label, Some(rule_label)),
        Rule::Opt(rule) => Count {
            min: 0,
            ..field_count(rule, target, label, active_label)
        },
        Rule::Rep(rule) => {
            let inner = field_count(rule, target, label, active_label);
            Count {
                min: 0,
                max: u8::from(inner.max != 0) * 2,
            }
        }
        Rule::Seq(rules) => rules.iter().fold(Count::ZERO, |count, rule| {
            count.sequence(field_count(rule, target, label, active_label))
        }),
        Rule::Alt(rules) => rules
            .iter()
            .map(|rule| field_count(rule, target, label, active_label))
            .reduce(Count::alternative)
            .unwrap_or(Count::ZERO),
    }
}

impl From<bool> for Count {
    fn from(present: bool) -> Self {
        if present { Self::ONE } else { Self::ZERO }
    }
}

fn accessor_method(
    grammar: &Grammar,
    target: AccessorTarget,
    cardinality: Cardinality,
    label: Option<&str>,
) -> String {
    if let Some(label) = label {
        return match target {
            AccessorTarget::Node(_) => label.to_owned(),
            AccessorTarget::Token(_) if cardinality == Cardinality::Many => {
                format!("{label}_tokens")
            }
            AccessorTarget::Token(_) => format!("{label}_token"),
        };
    }
    match target {
        AccessorTarget::Node(node) => {
            let singular = snake(&grammar[node].name);
            if cardinality == Cardinality::Many {
                plural_snake(&singular)
            } else if singular == "type" {
                "ty".to_owned()
            } else {
                singular
            }
        }
        AccessorTarget::Token(token) => {
            let variant = kind_variant(&format!("token:{}", grammar[token].name));
            let base = snake(&variant);
            let base = base.strip_prefix("kw_").unwrap_or(&base);
            if cardinality == Cardinality::Many {
                format!("{base}_tokens")
            } else {
                format!("{base}_token")
            }
        }
    }
}

fn render_pattern(
    rule: &Rule,
    grammar: &Grammar,
    labels: &[String],
    active_label: Option<&str>,
) -> String {
    match rule {
        Rule::Node(node) => render_pattern_atom(
            &kind_variant(&format!("node:{}", grammar[*node].name)),
            labels,
            active_label,
        ),
        Rule::Token(token) => render_pattern_atom(
            &kind_variant(&format!("token:{}", grammar[*token].name)),
            labels,
            active_label,
        ),
        Rule::Labeled { label, rule } => render_pattern(rule, grammar, labels, Some(label)),
        Rule::Opt(rule) => format!(
            "AstPattern::Opt(&{})",
            render_pattern(rule, grammar, labels, active_label)
        ),
        Rule::Rep(rule) => format!(
            "AstPattern::Rep(&{})",
            render_pattern(rule, grammar, labels, active_label)
        ),
        Rule::Seq(rules) => format!(
            "AstPattern::Seq(&[{}])",
            rules
                .iter()
                .map(|rule| render_pattern(rule, grammar, labels, active_label))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Rule::Alt(rules) => format!(
            "AstPattern::Alt(&[{}])",
            rules
                .iter()
                .map(|rule| render_pattern(rule, grammar, labels, active_label))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn render_pattern_atom(kind: &str, labels: &[String], active_label: Option<&str>) -> String {
    let label = active_label
        .and_then(|label| labels.iter().position(|candidate| candidate == label))
        .map_or_else(|| "None".to_owned(), |index| format!("Some({index})"));
    format!("AstPattern::Atom {{ kind: SyntaxKind::{kind}, label: {label} }}")
}

fn render_accessor(output: &mut String, grammar: &Grammar, owner: &TypedNode, accessor: &Accessor) {
    let method = &accessor.method;
    if let AccessorSelector::Label(label) = accessor.selector {
        render_labeled_accessor(output, grammar, owner, accessor, label);
        return;
    }
    match (accessor.target, accessor.cardinality) {
        (AccessorTarget::Node(node), Cardinality::Many) => {
            let child = &grammar[node].name;
            output.push_str(&format!(
                "\n    #[must_use]\n    pub fn {method}(&self) -> AstChildren<{child}> {{\n        support::children(&self.syntax)\n    }}\n"
            ));
        }
        (AccessorTarget::Node(node), _) => {
            let child = &grammar[node].name;
            output.push_str(&format!(
                "\n    #[must_use]\n    pub fn {method}(&self) -> Option<{child}> {{\n        support::child(&self.syntax)\n    }}\n"
            ));
        }
        (AccessorTarget::Token(token), Cardinality::Many) => {
            let kind = kind_variant(&format!("token:{}", grammar[token].name));
            output.push_str(&format!(
                "\n    #[must_use]\n    pub fn {method}(&self) -> impl Iterator<Item = SyntaxToken> + '_ {{\n        self.syntax.children_with_tokens().filter_map(rowan::NodeOrToken::into_token).filter(|token| token.kind() == SyntaxKind::{kind})\n    }}\n"
            ));
        }
        (AccessorTarget::Token(token), _) => {
            let kind = kind_variant(&format!("token:{}", grammar[token].name));
            output.push_str(&format!(
                "\n    #[must_use]\n    pub fn {method}(&self) -> Option<SyntaxToken> {{\n        support::token(&self.syntax, SyntaxKind::{kind})\n    }}\n"
            ));
        }
    }
}

fn render_labeled_accessor(
    output: &mut String,
    grammar: &Grammar,
    owner: &TypedNode,
    accessor: &Accessor,
    label: u16,
) {
    let method = &accessor.method;
    let pattern = format!(
        "AST_PATTERN_{}",
        snake(&grammar[owner.node].name).to_ascii_uppercase()
    );
    match (accessor.target, accessor.cardinality) {
        (AccessorTarget::Node(node), Cardinality::Many) => {
            let child = &grammar[node].name;
            output.push_str(&format!(
                "\n    #[must_use]\n    pub fn {method}(&self) -> impl Iterator<Item = {child}> {{\n        ast_fields(&self.syntax, &{pattern}, {label}).into_iter().flatten().filter_map(rowan::NodeOrToken::into_node).filter_map({child}::cast)\n    }}\n"
            ));
        }
        (AccessorTarget::Node(node), _) => {
            let child = &grammar[node].name;
            output.push_str(&format!(
                "\n    #[must_use]\n    pub fn {method}(&self) -> Option<{child}> {{\n        ast_fields(&self.syntax, &{pattern}, {label}).into_iter().next().flatten().and_then(rowan::NodeOrToken::into_node).and_then({child}::cast)\n    }}\n"
            ));
        }
        (AccessorTarget::Token(_), Cardinality::Many) => {
            output.push_str(&format!(
                "\n    #[must_use]\n    pub fn {method}(&self) -> impl Iterator<Item = SyntaxToken> {{\n        ast_fields(&self.syntax, &{pattern}, {label}).into_iter().flatten().filter_map(rowan::NodeOrToken::into_token)\n    }}\n"
            ));
        }
        (AccessorTarget::Token(_), _) => {
            output.push_str(&format!(
                "\n    #[must_use]\n    pub fn {method}(&self) -> Option<SyntaxToken> {{\n        ast_fields(&self.syntax, &{pattern}, {label}).into_iter().next().flatten().and_then(rowan::NodeOrToken::into_token)\n    }}\n"
            ));
        }
    }
}

fn kind_variant(key: &str) -> String {
    if key == "special:ERROR" {
        return "Error".into();
    }
    if let Some(value) = key.strip_prefix("node:") {
        return value.into();
    }
    if let Some(value) = key.strip_prefix("trivia:") {
        return pascal(value);
    }
    if let Some(value) = key.strip_prefix("special:") {
        return pascal(value);
    }
    let value = key.strip_prefix("token:").unwrap_or(key);
    match value {
        "EOF" => "Eof".into(),
        "Map" => "KwMapType".into(),
        "Prompt" => "KwPromptType".into(),
        "identifier" => "Ident".into(),
        "effect-id" => "EffectId".into(),
        "int-literal" => "IntLiteral".into(),
        "float-literal" => "FloatLiteral".into(),
        "string-literal" => "StringLiteral".into(),
        "bytes-literal" => "BytesLiteral".into(),
        "template-text-scalar" => "TemplateTextScalar".into(),
        "template-escape" => "TemplateEscape".into(),
        "{" => "LBrace".into(),
        "}" => "RBrace".into(),
        "[" => "LBracket".into(),
        "]" => "RBracket".into(),
        "(" => "LParen".into(),
        ")" => "RParen".into(),
        "," => "Comma".into(),
        ":" => "Colon".into(),
        ";" => "Semi".into(),
        "<" => "Lt".into(),
        ">" => "Gt".into(),
        "=" => "Eq".into(),
        "+=" => "PlusEq".into(),
        "-=" => "MinusEq".into(),
        "*=" => "StarEq".into(),
        "/=" => "SlashEq".into(),
        "%=" => "PercentEq".into(),
        ".." => "DotDot".into(),
        "_" => "Underscore".into(),
        "||" => "PipePipe".into(),
        "&&" => "AmpAmp".into(),
        "==" => "EqEq".into(),
        "!=" => "NotEq".into(),
        "<=" => "LtEq".into(),
        ">=" => "GtEq".into(),
        "+" => "Plus".into(),
        "-" => "Minus".into(),
        "*" => "Star".into(),
        "/" => "Slash".into(),
        "%" => "Percent".into(),
        "!" => "Bang".into(),
        "." => "Dot".into(),
        "?" => "Question".into(),
        "`" => "Backtick".into(),
        "${" => "TemplateExprStart".into(),
        "=>" => "FatArrow".into(),
        "@" => "At".into(),
        _ => format!("Kw{}", pascal(value)),
    }
}

fn pascal(value: &str) -> String {
    let mut output = String::new();
    for part in value
        .split(|character: char| !character.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
    {
        let mut characters = part.chars();
        output.push(characters.next().unwrap_or_default().to_ascii_uppercase());
        output.push_str(&characters.as_str().to_ascii_lowercase());
    }
    output
}

fn snake(name: &str) -> String {
    let mut output = String::new();
    for (index, character) in name.char_indices() {
        if character.is_ascii_uppercase() && index != 0 {
            output.push('_');
        }
        output.push(character.to_ascii_lowercase());
    }
    output
}

fn plural_snake(name: &str) -> String {
    if let Some(stem) = name.strip_suffix('y') {
        return format!("{stem}ies");
    }
    if name.ends_with('s') {
        return format!("{name}_items");
    }
    format!("{name}s")
}

