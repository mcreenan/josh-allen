/// Recovery structure retained directly beneath a typed AST wrapper.
#[derive(Clone, Debug, Eq, Hash, PartialEq)]
pub enum AstError {
    Error(SyntaxNode),
    Missing(SyntaxNode),
    ErrorToken(SyntaxToken),
}

impl AstError {
    fn cast(element: SyntaxElement) -> Option<Self> {
        match element {
            rowan::NodeOrToken::Node(node) if node.kind() == SyntaxKind::Error => Some(Self::Error(node)),
            rowan::NodeOrToken::Node(node) if node.kind() == SyntaxKind::Missing => Some(Self::Missing(node)),
            rowan::NodeOrToken::Token(token) if token.kind() == SyntaxKind::ErrorToken => Some(Self::ErrorToken(token)),
            _ => None,
        }
    }

    #[must_use]
    pub fn kind(&self) -> SyntaxKind {
        match self {
            Self::Error(node) | Self::Missing(node) => node.kind(),
            Self::ErrorToken(token) => token.kind(),
        }
    }
}

#[derive(Clone, Copy)]
enum AstPattern {
    Atom { kind: SyntaxKind, label: Option<u16> },
    Seq(&'static [AstPattern]),
    Alt(&'static [AstPattern]),
    Opt(&'static AstPattern),
    Rep(&'static AstPattern),
}

#[derive(Clone, Debug)]
struct AstCapture {
    previous: Option<Rc<Self>>,
    element: Option<SyntaxElement>,
}

#[derive(Clone, Debug)]
struct AstMatch {
    pos: usize,
    score: usize,
    field_count: usize,
    fields: Option<Rc<AstCapture>>,
}

fn ast_fields(node: &SyntaxNode, pattern: &AstPattern, label: u16) -> Vec<Option<SyntaxElement>> {
    ast_fields_with_work(node, pattern, label).0
}

fn ast_fields_with_work(
    node: &SyntaxNode,
    pattern: &AstPattern,
    label: u16,
) -> (Vec<Option<SyntaxElement>>, usize) {
    let elements = node
        .children_with_tokens()
        .filter(|element| {
            !matches!(
                element.kind(),
                SyntaxKind::Whitespace
                    | SyntaxKind::Newline
                    | SyntaxKind::LineComment
                    | SyntaxKind::BlockComment
                    | SyntaxKind::Error
                    | SyntaxKind::ErrorToken
            )
        })
        .collect::<Vec<_>>();
    let mut work = 0;
    let initial = AstMatch {
        pos: 0,
        score: 0,
        field_count: 0,
        fields: None,
    };
    let matches = if ast_has_nested_repetition(pattern, false) {
        ast_apply_automaton(pattern, &elements, initial, label, &mut work)
    } else {
        ast_apply(pattern, &elements, vec![initial], label, &mut work)
    };
    let fields = matches
        .into_iter()
        .max_by_key(|state| {
            (
                state.pos == elements.len(),
                state.pos,
                state.score,
                state.field_count,
            )
        })
        .map_or_else(Vec::new, ast_materialize_fields);
    (fields, work)
}

fn ast_materialize_fields(state: AstMatch) -> Vec<Option<SyntaxElement>> {
    let mut fields = Vec::with_capacity(state.field_count);
    let mut capture = state.fields;
    while let Some(current) = capture {
        fields.push(current.element.clone());
        capture = current.previous.clone();
    }
    fields.reverse();
    fields
}

fn ast_has_nested_repetition(pattern: &AstPattern, inside_repetition: bool) -> bool {
    match pattern {
        AstPattern::Rep(pattern) => {
            inside_repetition || ast_has_nested_repetition(pattern, true)
        }
        AstPattern::Opt(pattern) => ast_has_nested_repetition(pattern, inside_repetition),
        AstPattern::Seq(patterns) | AstPattern::Alt(patterns) => patterns
            .iter()
            .any(|pattern| ast_has_nested_repetition(pattern, inside_repetition)),
        AstPattern::Atom { .. } => false,
    }
}

#[derive(Clone, Copy)]
enum AstAutomatonEdge {
    Epsilon(usize),
    Atom {
        kind: SyntaxKind,
        label: Option<u16>,
        next: usize,
    },
}

struct AstAutomaton {
    edges: Vec<Vec<AstAutomatonEdge>>,
    start: usize,
    accept: usize,
}

impl AstAutomaton {
    fn compile(pattern: &AstPattern) -> Self {
        let mut automaton = Self {
            edges: Vec::new(),
            start: 0,
            accept: 0,
        };
        let (start, accept) = automaton.fragment(pattern);
        automaton.start = start;
        automaton.accept = accept;
        automaton
    }

    fn state(&mut self) -> usize {
        let state = self.edges.len();
        self.edges.push(Vec::new());
        state
    }

    fn epsilon(&mut self, from: usize, to: usize) {
        self.edges[from].push(AstAutomatonEdge::Epsilon(to));
    }

    fn fragment(&mut self, pattern: &AstPattern) -> (usize, usize) {
        match pattern {
            AstPattern::Atom { kind, label } => {
                let start = self.state();
                let accept = self.state();
                self.edges[start].push(AstAutomatonEdge::Atom {
                    kind: *kind,
                    label: *label,
                    next: accept,
                });
                (start, accept)
            }
            AstPattern::Seq(patterns) => {
                let start = self.state();
                let mut tail = start;
                for pattern in *patterns {
                    let (next_start, next_accept) = self.fragment(pattern);
                    self.epsilon(tail, next_start);
                    tail = next_accept;
                }
                (start, tail)
            }
            AstPattern::Alt(patterns) => {
                let start = self.state();
                let accept = self.state();
                for pattern in *patterns {
                    let (branch_start, branch_accept) = self.fragment(pattern);
                    self.epsilon(start, branch_start);
                    self.epsilon(branch_accept, accept);
                }
                (start, accept)
            }
            AstPattern::Opt(pattern) => {
                let start = self.state();
                let accept = self.state();
                let (inner_start, inner_accept) = self.fragment(pattern);
                self.epsilon(start, accept);
                self.epsilon(start, inner_start);
                self.epsilon(inner_accept, accept);
                (start, accept)
            }
            AstPattern::Rep(pattern) => {
                let start = self.state();
                let accept = self.state();
                let (inner_start, inner_accept) = self.fragment(pattern);
                self.epsilon(start, accept);
                self.epsilon(start, inner_start);
                self.epsilon(inner_accept, inner_start);
                self.epsilon(inner_accept, accept);
                (start, accept)
            }
        }
    }
}

fn ast_apply_automaton(
    pattern: &AstPattern,
    elements: &[SyntaxElement],
    initial: AstMatch,
    selected_label: u16,
    work: &mut usize,
) -> Vec<AstMatch> {
    let automaton = AstAutomaton::compile(pattern);
    let mut current = BTreeMap::from([(automaton.start, initial)]);
    let mut matches = Vec::new();
    for position in 0..=elements.len() {
        ast_automaton_epsilon_closure(&automaton, &mut current, work);
        if let Some(state) = current.get(&automaton.accept) {
            matches.push(state.clone());
        }
        let Some(element) = elements.get(position) else {
            break;
        };
        let actual = element.kind();
        let mut next = BTreeMap::new();
        for (state, matched) in &current {
            for edge in &automaton.edges[*state] {
                let AstAutomatonEdge::Atom { kind, label, next: target } = edge else {
                    continue;
                };
                *work += 1;
                if actual != *kind && actual != SyntaxKind::Missing {
                    continue;
                }
                let mut candidate = matched.clone();
                candidate.pos = position + 1;
                candidate.score += usize::from(actual == *kind);
                if *label == Some(selected_label) {
                    candidate.field_count += 1;
                    candidate.fields = Some(Rc::new(AstCapture {
                        previous: candidate.fields,
                        element: (actual != SyntaxKind::Missing).then(|| element.clone()),
                    }));
                }
                ast_insert_automaton_state(&mut next, *target, candidate);
            }
        }
        current = next;
    }
    matches
}

fn ast_automaton_epsilon_closure(
    automaton: &AstAutomaton,
    states: &mut BTreeMap<usize, AstMatch>,
    work: &mut usize,
) {
    let mut pending = states.keys().copied().collect::<VecDeque<_>>();
    while let Some(state) = pending.pop_front() {
        let matched = states
            .get(&state)
            .expect("pending automaton state must have a match")
            .clone();
        for edge in &automaton.edges[state] {
            let AstAutomatonEdge::Epsilon(target) = edge else {
                continue;
            };
            *work += 1;
            if ast_insert_automaton_state(states, *target, matched.clone()) {
                pending.push_back(*target);
            }
        }
    }
}

fn ast_insert_automaton_state(
    states: &mut BTreeMap<usize, AstMatch>,
    state: usize,
    candidate: AstMatch,
) -> bool {
    match states.get(&state) {
        Some(previous) if !ast_is_better(&candidate, previous) => false,
        _ => {
            states.insert(state, candidate);
            true
        }
    }
}

fn ast_apply(
    pattern: &AstPattern,
    elements: &[SyntaxElement],
    states: Vec<AstMatch>,
    selected_label: u16,
    work: &mut usize,
) -> Vec<AstMatch> {
    match pattern {
        AstPattern::Atom { kind, label } => {
            *work += states.len();
            ast_dedup(
                states
                    .into_iter()
                    .filter_map(|mut state| {
                        let element = elements.get(state.pos)?;
                        let actual = element.kind();
                        if actual != *kind && actual != SyntaxKind::Missing {
                            return None;
                        }
                        state.pos += 1;
                        state.score += usize::from(actual == *kind);
                        if *label == Some(selected_label) {
                            state.field_count += 1;
                            state.fields = Some(Rc::new(AstCapture {
                                previous: state.fields,
                                element: (actual != SyntaxKind::Missing)
                                    .then(|| element.clone()),
                            }));
                        }
                        Some(state)
                    })
                    .collect(),
            )
        }
        AstPattern::Seq(patterns) => patterns.iter().fold(states, |states, pattern| {
            ast_apply(pattern, elements, states, selected_label, work)
        }),
        AstPattern::Alt(patterns) => ast_dedup(
            patterns
                .iter()
                .flat_map(|pattern| {
                    ast_apply(
                        pattern,
                        elements,
                        ast_clone_states(&states, work),
                        selected_label,
                        work,
                    )
                })
                .collect(),
        ),
        AstPattern::Opt(pattern) => {
            let mut matches = ast_clone_states(&states, work);
            matches.extend(ast_apply(pattern, elements, states, selected_label, work));
            ast_dedup(matches)
        }
        AstPattern::Rep(pattern) => {
            let mut matches = ast_dedup(states)
                .into_iter()
                .map(|state| (state.pos, state))
                .collect::<BTreeMap<_, _>>();
            *work += matches.len();
            let mut pending = matches.keys().copied().collect::<BTreeSet<_>>();
            while let Some(position) = pending.pop_first() {
                let frontier = vec![matches
                    .get(&position)
                    .expect("pending repetition endpoint must have a match")
                    .clone()];
                let next = ast_apply(pattern, elements, frontier, selected_label, work);
                for state in ast_dedup(next) {
                    if state.pos <= position {
                        continue;
                    }
                    match matches.get(&state.pos) {
                        None => {
                            *work += 1;
                            pending.insert(state.pos);
                            matches.insert(state.pos, state);
                        }
                        Some(previous) if ast_is_better(&state, previous) => {
                            debug_assert!(
                                pending.contains(&state.pos),
                                "a forward repetition endpoint must improve before expansion"
                            );
                            matches.insert(state.pos, state);
                        }
                        Some(_) => {}
                    }
                }
            }
            matches.into_values().collect()
        }
    }
}

fn ast_clone_states(states: &[AstMatch], work: &mut usize) -> Vec<AstMatch> {
    *work += states.len();
    states.to_vec()
}

fn ast_is_better(candidate: &AstMatch, previous: &AstMatch) -> bool {
    (candidate.score, candidate.field_count) > (previous.score, previous.field_count)
}

fn ast_dedup(states: Vec<AstMatch>) -> Vec<AstMatch> {
    let mut best = BTreeMap::<usize, AstMatch>::new();
    for state in states {
        match best.get(&state.pos) {
            Some(previous) if !ast_is_better(&state, previous) => {}
            _ => {
                best.insert(state.pos, state);
            }
        }
    }
    best.into_values().collect()
}

