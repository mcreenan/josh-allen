//! Source control-flow construct records for the artifact debug section.
//!
//! Lowering records each source `for`, `while`, `loop`, `if`, `match`, and
//! `await` block with the contiguous instruction range it emits. Conditionals
//! that the compiler generates for short-circuit operators, `??`, and
//! decision-lowered patterns are not recorded.

use allen_bytecode::{DebugConstruct, DebugConstructKind, DebugRegion, DebugRegionKind};

use super::{FunctionLowering, LoweredPattern, Span};

/// The binding name that syntax lowering uses for `left ?? right`.
const COALESCED_VALUE: &str = "__allen_coalesced_value";

/// One construct recorded while its function is lowered.
///
/// `parent` is an index into the same function's construct list.
#[derive(Clone, Debug)]
pub(in crate::frontend) struct PendingConstruct {
    parent: Option<usize>,
    kind: DebugConstructKind,
    span: Span,
    first_instruction: usize,
    end_instruction: usize,
    regions: Vec<DebugRegion>,
    repeat_edges: Vec<usize>,
}

/// A region described by its kind and source span before it is recorded.
pub(super) type RegionSpan = (DebugRegionKind, Span);

impl FunctionLowering<'_, '_> {
    /// Open a construct at the current instruction unless it was generated by
    /// pattern lowering. Returns the construct's local index.
    pub(super) fn begin_construct(
        &mut self,
        kind: DebugConstructKind,
        span: Span,
    ) -> Option<usize> {
        if self
            .generated_construct_spans
            .iter()
            .any(|spans| spans.contains(&span))
        {
            return None;
        }
        let index = self.constructs.len();
        self.constructs.push(PendingConstruct {
            parent: self.construct_stack.last().copied(),
            kind,
            span,
            first_instruction: self.code.len(),
            end_instruction: self.code.len(),
            regions: Vec::new(),
            repeat_edges: Vec::new(),
        });
        self.construct_stack.push(index);
        Some(index)
    }

    /// Close a construct at the current instruction with its regions and
    /// repeat edges.
    pub(super) fn finish_construct(
        &mut self,
        index: Option<usize>,
        regions: &[RegionSpan],
        repeat_edges: &[usize],
    ) {
        let Some(index) = index else {
            return;
        };
        while let Some(open) = self.construct_stack.pop() {
            if open == index {
                break;
            }
        }
        let end_instruction = self.code.len();
        let mut arm = 0;
        let regions = regions
            .iter()
            .map(|(kind, span)| {
                let index = if *kind == DebugRegionKind::Arm {
                    arm += 1;
                    arm - 1
                } else {
                    0
                };
                DebugRegion {
                    kind: *kind,
                    index,
                    start: u32::try_from(span.start).unwrap_or(u32::MAX),
                    end: u32::try_from(span.end).unwrap_or(u32::MAX),
                }
            })
            .collect();
        let mut repeat_edges = repeat_edges
            .iter()
            .copied()
            .filter(|edge| *edge < end_instruction)
            .collect::<Vec<_>>();
        repeat_edges.sort_unstable();
        repeat_edges.dedup();
        let construct = &mut self.constructs[index];
        construct.end_instruction = end_instruction;
        construct.regions = regions;
        construct.repeat_edges = repeat_edges;
    }

    /// Discard constructs recorded at or after `instruction` when emitted code
    /// is truncated.
    pub(super) fn truncate_constructs_from(&mut self, instruction: usize) {
        while self
            .constructs
            .last()
            .is_some_and(|construct| construct.first_instruction >= instruction)
        {
            let removed = self.constructs.len() - 1;
            self.constructs.pop();
            self.construct_stack.retain(|open| *open != removed);
        }
    }

    /// Run `compile` while suppressing constructs whose span is one of the
    /// spans that pattern lowering assigns to its generated conditionals.
    pub(super) fn with_generated_construct_spans<T>(
        &mut self,
        spans: Vec<Span>,
        compile: impl FnOnce(&mut Self) -> T,
    ) -> T {
        self.generated_construct_spans.push(spans);
        let result = compile(self);
        self.generated_construct_spans.pop();
        result
    }
}

/// Whether a match was produced by syntax lowering of `left ?? right`.
pub(super) fn is_coalescing_match(arms: &[(LoweredPattern, super::LoweredExpr, Span)]) -> bool {
    matches!(
        arms,
        [_, (LoweredPattern::Option { some: true, payload: Some(payload) }, _, _)]
            if matches!(payload.as_ref(), LoweredPattern::Binding { name, .. } if name == COALESCED_VALUE)
    )
}

/// Every span that decision lowering of these arms can give a generated
/// conditional: the match span, each arm's pattern span, and every nested
/// record-field span.
pub(super) fn generated_pattern_spans(
    span: Span,
    arms: &[(LoweredPattern, super::LoweredExpr, Span)],
) -> Vec<Span> {
    fn nested(pattern: &LoweredPattern, spans: &mut Vec<Span>) {
        match pattern {
            LoweredPattern::Binding { span, .. } => spans.push(*span),
            LoweredPattern::Record { fields, .. }
            | LoweredPattern::Enum {
                fields: Some(fields),
                ..
            } => {
                for (_, field_span, pattern) in fields {
                    spans.push(*field_span);
                    nested(pattern, spans);
                }
            }
            LoweredPattern::Enum { patterns, .. } => {
                for pattern in patterns {
                    nested(pattern, spans);
                }
            }
            LoweredPattern::Option {
                payload: Some(payload),
                ..
            }
            | LoweredPattern::Result { payload, .. } => nested(payload, spans),
            LoweredPattern::Or {
                alternatives,
                operator_spans,
            } => {
                spans.extend(operator_spans);
                for alternative in alternatives {
                    nested(alternative, spans);
                }
            }
            LoweredPattern::Wildcard
            | LoweredPattern::Bool(_)
            | LoweredPattern::Option { payload: None, .. }
            | LoweredPattern::Range { .. } => {}
        }
    }
    let mut spans = vec![span];
    for (pattern, _, pattern_span) in arms {
        spans.push(*pattern_span);
        nested(pattern, &mut spans);
    }
    spans.sort_by_key(|span| (span.start, span.end));
    spans.dedup();
    spans
}

/// Convert one function's pending constructs into debug records.
///
/// Constructs with an empty instruction range are dropped and their children
/// are re-parented to the nearest recorded ancestor. Parents remain local
/// indexes; the driver rebases them once every function is lowered.
pub(in crate::frontend) fn finish_function_constructs(
    constructs: &[PendingConstruct],
    function: u32,
    source: u32,
) -> Vec<DebugConstruct> {
    let mut kept: Vec<Option<usize>> = Vec::with_capacity(constructs.len());
    let mut output = Vec::new();
    for construct in constructs {
        let mut parent = construct.parent;
        while let Some(index) = parent {
            if kept[index].is_some() {
                break;
            }
            parent = constructs[index].parent;
        }
        if construct.first_instruction >= construct.end_instruction {
            kept.push(None);
            continue;
        }
        kept.push(Some(output.len()));
        output.push(DebugConstruct {
            function,
            parent: parent
                .and_then(|index| kept[index])
                .map(|index| u32::try_from(index).expect("construct index fits")),
            kind: construct.kind,
            source,
            start: u32::try_from(construct.span.start).unwrap_or(u32::MAX),
            end: u32::try_from(construct.span.end).unwrap_or(u32::MAX),
            first_instruction: u32::try_from(construct.first_instruction)
                .expect("instruction ID fits"),
            end_instruction: u32::try_from(construct.end_instruction).expect("instruction ID fits"),
            regions: construct.regions.clone(),
            repeat_edges: construct
                .repeat_edges
                .iter()
                .map(|edge| u32::try_from(*edge).expect("instruction ID fits"))
                .collect(),
        });
    }
    output
}

/// Order constructs by function, keep each function's pre-order, and rebase
/// function-local parent indexes onto table positions.
pub(in crate::frontend) fn finish_module_constructs(
    mut constructs: Vec<DebugConstruct>,
) -> Vec<DebugConstruct> {
    constructs.sort_by_key(|construct| construct.function);
    let mut function_start = 0;
    for index in 0..constructs.len() {
        if index > 0 && constructs[index - 1].function != constructs[index].function {
            function_start = index;
        }
        if let Some(parent) = constructs[index].parent.as_mut() {
            *parent += u32::try_from(function_start).expect("construct index fits");
        }
    }
    constructs
}
